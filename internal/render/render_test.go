func TestDeepMerge(t *testing.T) {
	dst := map[string]any{"a": 1, "m": map[string]any{"x": 1, "y": []any{1}}, "k": "v"}
	src := map[string]any{
		"a": "s",
		"m": map[any]any{"y": []any{2, 3}, "z": map[string]any{"q": true}},
		"k": nil,
		"n": map[string]any{"deep": nil, "keep": 1},
	}
	got := deepMerge(dst, src)
	b, _ := json.Marshal(got)
	want := `{"a":"s","m":{"x":1,"y":[2,3],"z":{"q":true}},"n":{"keep":1}}`
	if string(b) != want {
		t.Errorf("got %s\nwant %s", b, want)
	}
	// src must not be aliased.
	src["m"].(map[any]any)["z"].(map[string]any)["q"] = false
	if got["m"].(map[string]any)["z"].(map[string]any)["q"] != true {
		t.Error("deepMerge aliased src")
	}
}
