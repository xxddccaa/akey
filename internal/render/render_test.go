var update = flag.Bool("update", false, "rewrite golden files under testdata/golden")

const examplePath = "../../testdata/master.example.yaml"

func loadExample(t *testing.T) *spec.Master {
	t.Helper()
	m, err := spec.Load(examplePath)
	if err != nil {
		t.Fatal(err)
	}
	return m
}

// TestGolden renders the example master for every tool and compares with
// testdata/golden/<tool>/<relpath>. Run `go test ./internal/render -update`
// after an intentional format change.
func TestGolden(t *testing.T) {
	m := loadExample(t)
	files, err := RenderAll(m, nil)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]bool{}
	for _, f := range files {
		p := filepath.Join("testdata", "golden", f.Tool, filepath.FromSlash(f.RelPath))
		got[filepath.ToSlash(p)] = true
		if *update {
			if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(p, f.Content, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		want, err := os.ReadFile(p)
		if err != nil {
			t.Errorf("%s: %v (run with -update)", p, err)
			continue
		}
		if !bytes.Equal(want, f.Content) {
			t.Errorf("%s differs from golden (run with -update to accept):\n%s", p, f.Content)
		}
	}
	// No stale golden files.
	filepath.Walk(filepath.Join("testdata", "golden"), func(p string, fi os.FileInfo, err error) error {
		if err == nil && !fi.IsDir() && !got[filepath.ToSlash(p)] {
			t.Errorf("stale golden file %s", p)
		}
		return nil
	})
}

func TestDeterministic(t *testing.T) {
	a, err := RenderAll(loadExample(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	for i := 0; i < 5; i++ {
		b, err := RenderAll(loadExample(t), nil)
		if err != nil {
			t.Fatal(err)
		}
		if len(a) != len(b) {
			t.Fatal("file count changed")
		}
		for j := range a {
			if a[j].RelPath != b[j].RelPath || !bytes.Equal(a[j].Content, b[j].Content) {
				t.Fatalf("%s/%s not deterministic", a[j].Tool, a[j].RelPath)
			}
		}
	}
}

func TestParsesAndModes(t *testing.T) {
	m := loadExample(t)
	files, err := RenderAll(m, nil)
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]uint32{
		"codex/config.toml":       0o600,
		"codex/AGENTS.md":         0o644,
		"xdcode/config.toml":      0o600,
		"claude/settings.json":    0o600,
		"claude/CLAUDE.md":        0o644,
		"opencode/opencode.jsonc": 0o600,
		"pi/models.json":          0o600,
		"pi/settings.json":        0o644,
	}
	if len(files) != len(want) {
		t.Errorf("got %d files, want %d", len(files), len(want))
	}
	for _, f := range files {
		k := f.Tool + "/" + f.RelPath
		mode, ok := want[k]
		if !ok {
			t.Errorf("unexpected file %s", k)
			continue
		}
		if f.Mode != mode {
			t.Errorf("%s: mode %o, want %o", k, f.Mode, mode)
		}
		var v map[string]any
		switch {
		case strings.HasSuffix(k, ".toml"):
			if !bytes.HasPrefix(f.Content, []byte("# Generated by akey")) {
				t.Errorf("%s: missing header", k)
			}
			if err := toml.Unmarshal(f.Content, &v); err != nil {
				t.Errorf("%s: invalid TOML: %v", k, err)
			}
		case strings.HasSuffix(k, ".jsonc"):
			if !bytes.HasPrefix(f.Content, []byte("// Generated by akey")) {
				t.Errorf("%s: missing header", k)
			}
			if err := json.Unmarshal(stripLineComments(f.Content), &v); err != nil {
				t.Errorf("%s: invalid JSONC: %v", k, err)
			}
		case strings.HasSuffix(k, ".json"):
			if err := json.Unmarshal(f.Content, &v); err != nil {
				t.Errorf("%s: invalid JSON: %v", k, err)
			}
		}
	}
}

func stripLineComments(b []byte) []byte {
	var out [][]byte
	for _, l := range bytes.Split(b, []byte("\n")) {
		if !bytes.HasPrefix(bytes.TrimSpace(l), []byte("//")) {
			out = append(out, l)
		}
	}
	return bytes.Join(out, []byte("\n"))
}

// mustDoc renders one tool and decodes its main document.
func mustDoc(t *testing.T, m *spec.Master, tool, rel string) map[string]any {
	t.Helper()
	files, err := Render(m, tool)
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range files {
		if f.RelPath != rel {
			continue
		}
		var v map[string]any
		if strings.HasSuffix(rel, ".toml") {
			err = toml.Unmarshal(f.Content, &v)
		} else {
			err = json.Unmarshal(stripLineComments(f.Content), &v)
		}
		if err != nil {
			t.Fatal(err)
		}
		return v
	}
	t.Fatalf("%s: no %s", tool, rel)
	return nil
}

func dig(v any, path ...string) any {
	for _, p := range path {
		m, ok := v.(map[string]any)
		if !ok {
			return nil
		}
		v = m[p]
	}
	return v
}

func TestExtraOverridesAndNullDeletes(t *testing.T) {
	m := loadExample(t)
	m.Tools["codex"].Extra = map[string]any{
		"model":           "forced",
		"model_providers": map[string]any{"relay": map[string]any{"supports_websockets": nil, "name": "X"}},
	}
	doc := mustDoc(t, m, "codex", "config.toml")
	if doc["model"] != "forced" {
		t.Errorf("extra did not override model: %v", doc["model"])
	}
	blk := dig(doc, "model_providers", "relay").(map[string]any)
	if _, ok := blk["supports_websockets"]; ok {
		t.Error("null in extra should delete the key")
	}
	if blk["name"] != "X" || blk["base_url"] == nil {
		t.Errorf("deep merge broke provider block: %v", blk)
	}
	// Master must not be mutated by rendering.
	if _, err := Render(m, "codex"); err != nil {
		t.Fatal(err)
	}
	if m.Tools["codex"].Extra["model_providers"].(map[string]any)["relay"].(map[string]any)["supports_websockets"] != nil {
		t.Error("master mutated")
	}
}

func TestSplitProvider(t *testing.T) {
	m := loadExample(t)
	oc := mustDoc(t, m, "opencode", "opencode.jsonc")
	if oc["model"] != "hybrid-anthropic/claude-opus-5.5" {
		t.Errorf("opencode model = %v", oc["model"])
	}
	if dig(oc, "provider", "hybrid", "npm") != npmOpenAI || dig(oc, "provider", "hybrid-anthropic", "npm") != npmAnthropic {
		t.Errorf("split providers wrong: %v", oc["provider"])
	}
	if got := dig(oc, "provider", "hybrid-anthropic", "options", "baseURL"); got != "https://api.hybrid.example.com/v1" {
		t.Errorf("anthropic baseURL = %v", got)
	}
	pi := mustDoc(t, m, "pi", "models.json")
	if dig(pi, "providers", "hybrid-anthropic", "api") != "anthropic-messages" {
		t.Errorf("pi split wrong: %v", dig(pi, "providers"))
	}
	if dig(pi, "providers", "hybrid") != nil {
		t.Error("pi should not get hybrid's openai side (model filtered by tools)")
	}

	// Collision with a real provider id is an error.
	m.Providers["hybrid-anthropic"] = &spec.Provider{Name: "x", OpenAI: &spec.OpenAIEndpoint{BaseURL: "http://x/v1", Wire: "responses"}}
	if _, err := Render(m, "opencode"); err == nil {
		t.Error("expected collision error")
	}
}

func TestPiThinkingMap(t *testing.T) {
	cases := []struct {
		efforts []string
		want    map[string]any
	}{
		{nil, nil},
		{[]string{"low", "medium", "high", "xhigh", "max"}, map[string]any{
			"off": nil, "minimal": nil, "low": "low", "medium": "medium", "high": "high", "xhigh": "xhigh"}},
		{[]string{"none", "low", "high", "max"}, map[string]any{
			"off": "none", "minimal": nil, "low": "low", "medium": nil, "high": "high", "xhigh": "max"}},
		{[]string{"minimal", "high"}, map[string]any{
			"off": nil, "minimal": "minimal", "low": nil, "medium": nil, "high": "high", "xhigh": nil}},
	}
	for _, c := range cases {
		got := piThinkingMap(c.efforts)
		gb, _ := json.Marshal(got)
		wb, _ := json.Marshal(c.want)
		if string(gb) != string(wb) {
			t.Errorf("%v: got %s want %s", c.efforts, gb, wb)
		}
	}
	for in, want := range map[string]string{"": "", "none": "off", "minimal": "minimal", "high": "high", "xhigh": "xhigh", "max": "xhigh", "ultra": "xhigh", "weird": ""} {
		if got := piLevel(in); got != want {
			t.Errorf("piLevel(%q) = %q, want %q", in, got, want)
		}
	}
}

